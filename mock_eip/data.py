def _curve(points, start="2025-09-10 10:00:00", step_s=3):
    base = datetime.strptime(start, "%Y-%m-%d %H:%M:%S")
    return [
        ((base + timedelta(seconds=step_s * i)).strftime("%Y-%m-%d %H:%M:%S"), kv, pc)
        for i, (kv, pc) in enumerate(points)
    ]


